#!/usr/bin/env python3
"""Mirror a UZH-FPV sequence into the EuRoC layout ORB-SLAM3's examples read.

ORB-SLAM3 (vendored, kept unpatched) has no UZH-FPV reader. Its
mono_inertial_euroc example reads <seq>/mav0/cam0/data/<ns>.png listed in a
timestamps file and <seq>/mav0/imu0/data.csv, so this script writes:

  OUT_DIR/mav0/cam0/data/<ns>.png   symlinks to the sequence's img/image_0_*.png
  OUT_DIR/mav0/cam0/data.csv        EuRoC image list
  OUT_DIR/mav0/imu0/data.csv        EuRoC IMU csv (ns, gyro xyz, accel xyz)
  OUT_DIR/timestamps.txt            the frame list for mono_inertial_euroc
  OUT_DIR/orbslam3_monoi.yaml       ORB-SLAM3 settings: KannalaBrandt8 camera,
                                    T_b_c1 and IMU noise from the Kalibr files
                                    (--settings-name and the --orb-* options
                                    write a variant next to it)

Camera timestamps are moved onto the IMU clock with Kalibr's
timeshift_cam_imu (t_imu = t_cam + shift), which ORB-SLAM3's settings have no
field for. wslam's UzhFpvProvider applies the same cam0 shift, so both systems
see the same timestamps, and both are scored against groundtruth.txt (IMU
pose, IMU clock).

Usage: uzh_fpv_to_euroc.py SEQUENCE_DIR CALIBRATION_DIR OUT_DIR
  SEQUENCE_DIR     — unpacked *_snapdragon_with_gt.zip (left_images.txt, imu.txt, img/)
  CALIBRATION_DIR  — unpacked *_calib_snapdragon.zip (camchain-imucam-*.yaml, imu.yaml)
"""

from __future__ import annotations

import argparse
import sys
from decimal import Decimal
from pathlib import Path

import yaml

NANOSECONDS_PER_SECOND = Decimal(1_000_000_000)


def seconds_to_ns(text: str) -> int:
    """Exact seconds -> ns (a float keeps only ~0.2 us at these magnitudes)."""
    return int(Decimal(text) * NANOSECONDS_PER_SECOND)


def read_rows(path: Path, columns: int) -> list[list[str]]:
    rows = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split()
        if len(fields) != columns:
            raise ValueError(f"{path}:{number}: expected {columns} columns, got {len(fields)}")
        rows.append(fields)
    return rows


def find_camchain(calibration_dir: Path) -> Path:
    found = sorted(calibration_dir.glob("camchain-imucam-*.yaml"))
    if len(found) != 1:
        raise FileNotFoundError(
            f"expected one camchain-imucam-*.yaml in {calibration_dir}, found {len(found)}")
    return found[0]


def invert_rigid(matrix: list[list[float]]) -> list[list[float]]:
    rotation_t = [[matrix[col][row] for col in range(3)] for row in range(3)]
    translation = [-sum(rotation_t[row][k] * matrix[k][3] for k in range(3)) for row in range(3)]
    return [rotation_t[row] + [translation[row]] for row in range(3)] + [[0.0, 0.0, 0.0, 1.0]]


def real(value: float) -> str:
    """A float OpenCV's FileStorage reads back as a real: `500` is an integer
    to it, and ORB-SLAM3 rejects integer reals."""
    text = f"{value:.17g}"
    return text if any(c in text for c in ".en") else text + ".0"


def orbslam_settings(camera: dict, imu: dict, fps: int, features: int,
                     ini_fast: int, min_fast: int) -> str:
    if camera["distortion_model"] != "equidistant" or camera["camera_model"] != "pinhole":
        raise ValueError("only pinhole + equidistant (KannalaBrandt8) cameras are supported, "
                         f"got {camera['camera_model']} + {camera['distortion_model']}")
    fx, fy, cx, cy = camera["intrinsics"]
    k1, k2, k3, k4 = camera["distortion_coeffs"]
    width, height = camera["resolution"]
    body_from_camera = invert_rigid(camera["T_cam_imu"])
    matrix = ",\n          ".join(", ".join(real(value) for value in row)
                                   for row in body_from_camera)
    return f"""%YAML:1.0
# Generated by benchmarks/uzh_fpv_to_euroc.py from the Kalibr calibration
File.version: "1.0"

Camera.type: "KannalaBrandt8"

Camera1.fx: {real(fx)}
Camera1.fy: {real(fy)}
Camera1.cx: {real(cx)}
Camera1.cy: {real(cy)}

Camera1.k1: {real(k1)}
Camera1.k2: {real(k2)}
Camera1.k3: {real(k3)}
Camera1.k4: {real(k4)}

Camera.width: {width}
Camera.height: {height}
Camera.fps: {fps}
Camera.RGB: 1

# Body (IMU) from camera: the inverse of Kalibr's T_cam_imu
IMU.T_b_c1: !!opencv-matrix
   rows: 4
   cols: 4
   dt: f
   data: [{matrix}]

# Kalibr imu.yaml, continuous-time densities
IMU.NoiseGyro: {real(imu["gyroscope_noise_density"])}
IMU.NoiseAcc: {real(imu["accelerometer_noise_density"])}
IMU.GyroWalk: {real(imu["gyroscope_random_walk"])}
IMU.AccWalk: {real(imu["accelerometer_random_walk"])}
IMU.Frequency: {real(imu["update_rate"])}

# Defaults: TUM-VI's fisheye settings, ORB-SLAM3's closest shipped configuration
ORBextractor.nFeatures: {features}
ORBextractor.scaleFactor: 1.2
ORBextractor.nLevels: 8
ORBextractor.iniThFAST: {ini_fast}
ORBextractor.minThFAST: {min_fast}

Viewer.KeyFrameSize: 0.05
Viewer.KeyFrameLineWidth: 1.0
Viewer.GraphLineWidth: 0.9
Viewer.PointSize: 2.0
Viewer.CameraSize: 0.08
Viewer.CameraLineWidth: 3.0
Viewer.ViewpointX: 0.0
Viewer.ViewpointY: -0.7
Viewer.ViewpointZ: -3.5
Viewer.ViewpointF: 500.0
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sequence_dir", type=Path)
    parser.add_argument("calibration_dir", type=Path)
    parser.add_argument("out_dir", type=Path)
    parser.add_argument("--orb-features", type=int, default=1250,
                        help="ORBextractor.nFeatures (default 1250, as TUM-VI)")
    parser.add_argument("--orb-fast", type=int, nargs=2, default=(20, 7),
                        metavar=("INI", "MIN"),
                        help="ORBextractor.iniThFAST / minThFAST (default 20 7)")
    parser.add_argument("--settings-name", default="orbslam3_monoi.yaml",
                        help="file name of the ORB-SLAM3 settings in OUT_DIR")
    args = parser.parse_args()

    sequence_dir = args.sequence_dir.resolve()
    camchain = yaml.safe_load(find_camchain(args.calibration_dir).read_text(encoding="utf-8"))
    imu = yaml.safe_load((args.calibration_dir / "imu.yaml").read_text(encoding="utf-8"))
    # The calibration zips' imu.yaml holds the imu0 block without its key
    imu = imu.get("imu0", imu)
    camera = camchain["cam0"]
    shift_ns = int(Decimal(str(camera.get("timeshift_cam_imu", 0.0))) * NANOSECONDS_PER_SECOND)

    mav0 = args.out_dir / "mav0"
    cam_data = mav0 / "cam0" / "data"
    imu_dir = mav0 / "imu0"
    cam_data.mkdir(parents=True, exist_ok=True)
    imu_dir.mkdir(parents=True, exist_ok=True)

    frames = []
    for _, stamp, image in read_rows(sequence_dir / "left_images.txt", 3):
        frames.append((seconds_to_ns(stamp) + shift_ns, sequence_dir / image))
    frames.sort()
    for timestamp, source in frames:
        link = cam_data / f"{timestamp}.png"
        if link.is_symlink() or link.exists():
            link.unlink()
        link.symlink_to(source)
    with (mav0 / "cam0" / "data.csv").open("w", encoding="utf-8") as f:
        f.write("#timestamp [ns],filename\n")
        f.writelines(f"{timestamp},{timestamp}.png\n" for timestamp, _ in frames)
    (args.out_dir / "timestamps.txt").write_text(
        "".join(f"{timestamp}\n" for timestamp, _ in frames), encoding="utf-8")

    with (imu_dir / "data.csv").open("w", encoding="utf-8") as f:
        f.write("#timestamp [ns],w_RS_S_x [rad s^-1],w_RS_S_y [rad s^-1],w_RS_S_z [rad s^-1],"
                "a_RS_S_x [m s^-2],a_RS_S_y [m s^-2],a_RS_S_z [m s^-2]\n")
        for row in read_rows(sequence_dir / "imu.txt", 8):
            f.write(",".join([str(seconds_to_ns(row[1]))] + row[2:]) + "\n")

    intervals = sorted(b[0] - a[0] for a, b in zip(frames, frames[1:]))
    fps = round(1e9 / intervals[len(intervals) // 2])
    settings = orbslam_settings(camera, imu, fps, args.orb_features, *args.orb_fast)
    (args.out_dir / args.settings_name).write_text(settings, encoding="utf-8")
    print(f"{len(frames)} frames at {fps} Hz, camera shift {shift_ns / 1e6:+.3f} ms -> {args.out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
