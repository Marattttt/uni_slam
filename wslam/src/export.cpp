std::optional<std::string> wslam::ExportMap(const AnyBag& storage,
                                            const ExportOpts& opts) {
    spdlog::info(LOG_ID " Exporting map to '{}'", opts.map_path.string());

    if (opts.map_path.empty()) {
        return "ExportMap: map_path is empty";
    }
    if (opts.map_path.extension() != ".ply") {
        return std::format(
            "ExportMap: map_path must end in '.ply' (got '{}')",
            opts.map_path.extension().string());
    }

    const auto meta_path_opt = deriveMetadataPath(opts.map_path);
    if (!meta_path_opt.has_value()) {
        return "ExportMap: failed to derive JSON sidecar path";
    }
    const auto& meta_path = meta_path_opt.value();

    const auto snap_ptr
        = storage.getPtr<MapSnapshot>(ResourceIdentifier::MapSnapshotName);
    const auto vio_ptr
        = storage.getPtr<MapSnapshot>(ResourceIdentifier::MapSnapshotVioName);
    const auto pgo_ptr
        = storage.getPtr<MapSnapshot>(ResourceIdentifier::MapSnapshotPgoName);
    const auto report_ptr = storage.getPtr<LoopClosureReport>(
        ResourceIdentifier::LoopClosureReportName);
    const LoopClosureReport* report
        = report_ptr.has_value() ? report_ptr.value() : nullptr;
    if (!snap_ptr.has_value()) {
        return std::format("ExportMap: no MapSnapshot under key '{}'",
                           ResourceIdentifier::MapSnapshotName);
    }
    const auto& snap = *snap_ptr.value();

    const auto cam_key
        = ResourceIdentifier::GetCameraIntrinsicsName(opts.camera_index);
    const auto cam_ptr = storage.getPtr<data::CamSensorParams>(cam_key);
    if (!cam_ptr.has_value()) {
        return std::format("ExportMap: no CamSensorParams under key '{}'",
                           cam_key);
    }
    const auto& cam = *cam_ptr.value();

    // Make sure the output directory exists; create it if asked for a fresh
    // path. Caller-provided directories that *should* already exist (e.g. a
    // shared output volume) are unaffected because create_directories is a
    // no-op when the path is already present.
    if (opts.map_path.has_parent_path()) {
        std::error_code ec;
        std::filesystem::create_directories(opts.map_path.parent_path(), ec);
        if (ec) {
            return std::format("ExportMap: cannot create output dir '{}': {}",
                               opts.map_path.parent_path().string(),
                               ec.message());
        }
    }

    if (auto err = writePly(opts.map_path, snap.landmarks)) {
        return std::format("writing PLY: {}", err.value());
    }
    // With loop closure the main files hold the corrected map (bundle
    // adjusted when a global BA ran), <stem>_vio.* the smoother's own and
    // <stem>_pgo.* the pose graph's correction before the adjustment
    const bool has_vio = vio_ptr.has_value();
    const bool has_pgo = pgo_ptr.has_value();
    if (auto err = writeJson(meta_path, snap, cam, report,
                             has_pgo   ? "global_ba"
                             : has_vio ? "loop_corrected"
                                       : "vio")) {
        return std::format("writing JSON metadata: {}", err.value());
    }

    const auto write_sibling
        = [&](const MapSnapshot& sibling, std::string_view suffix,
              std::string_view trajectory) -> std::optional<std::string> {
        std::filesystem::path sibling_map = opts.map_path;
        sibling_map.replace_filename(
            std::format("{}_{}.ply", opts.map_path.stem().string(), suffix));
        std::filesystem::path sibling_meta = sibling_map;
        sibling_meta.replace_extension(".json");

        if (auto err = writePly(sibling_map, sibling.landmarks)) {
            return std::format("writing {} PLY: {}", suffix, err.value());
        }
        if (auto err
            = writeJson(sibling_meta, sibling, cam, report, trajectory)) {
            return std::format("writing {} JSON metadata: {}", suffix,
                               err.value());
        }
        spdlog::info(LOG_ID " Wrote the {} map to '{}'", trajectory,
                     sibling_meta.string());
        return std::nullopt;
    };
    if (has_vio) {
        if (auto err = write_sibling(*vio_ptr.value(), "vio", "vio")) {
            return err;
        }
    }
    if (has_pgo) {
        if (auto err
            = write_sibling(*pgo_ptr.value(), "pgo", "loop_corrected")) {
            return err;
        }
    }

    spdlog::info(LOG_ID " Wrote map: {} landmarks → '{}', {} keyframes → '{}'",
                 snap.landmarks.size(), opts.map_path.string(),
                 snap.keyframes.size(), meta_path.string());

    return std::nullopt;
}
