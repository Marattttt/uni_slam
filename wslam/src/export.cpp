constexpr int kFormatVersion = 1;

// Returns the JSON sidecar path derived from a .ply map path by replacing the
// extension. Errors out if the input does not look like a `.ply` file so the
// pairing stays predictable for the Python viewer.
std::optional<std::filesystem::path> deriveMetadataPath(
    const std::filesystem::path& map_path) {
    if (map_path.empty()) {
        return std::nullopt;
    }
    std::filesystem::path out = map_path;
    out.replace_extension(".json");
    return out;
}

// ASCII PLY writer kept inline because the format is tiny and pulling a
// dependency for ~20 lines of header + per-vertex floats would be overkill.
// The `landmark_id` property survives loading by anything that respects PLY
// custom properties (plyfile, Open3D, meshlab).
std::optional<std::string> writePly(
    const std::filesystem::path& path,
    const std::vector<LandmarkEstimate>& landmarks) {
    std::ofstream f(path);
    if (!f) {
        return std::format("could not open '{}' for writing", path.string());
    }

    f << "ply\n"
      << "format ascii 1.0\n"
      << "comment generated by pc_wslam export\n"
      << "element vertex " << landmarks.size() << "\n"
      << "property float x\n"
      << "property float y\n"
      << "property float z\n"
      << "property uint landmark_id\n"
      << "end_header\n";

    for (const auto& lm : landmarks) {
        f << static_cast<float>(lm.position_world.x()) << ' '
          << static_cast<float>(lm.position_world.y()) << ' '
          << static_cast<float>(lm.position_world.z()) << ' '
          << lm.id.v << '\n';
    }

    if (!f) {
        return std::format("write error on '{}'", path.string());
    }
    return std::nullopt;
}

json poseToJson(const KeyframePose& kf) {
    json r = json::array();
    for (Eigen::Index row = 0; row < 3; ++row) {
        json row_arr = json::array();
        for (Eigen::Index col = 0; col < 3; ++col) {
            row_arr.push_back(kf.R_world_cam(row, col));
        }
        r.push_back(std::move(row_arr));
    }
    return json{
        {"id", kf.id.v},
        {"timestamp_ns", kf.timestamp_ns},
        {"R_world_cam", r},
        {"t_world_cam",
         json::array({kf.t_world_cam.x(), kf.t_world_cam.y(),
                      kf.t_world_cam.z()})},
    };
}

json cameraToJson(const data::CamSensorParams& cam) {
    return json{
        {"fx", cam.intrinsics(0)},        {"fy", cam.intrinsics(1)},
        {"cx", cam.intrinsics(2)},        {"cy", cam.intrinsics(3)},
        {"k1", cam.distortion_coefficients(0)},
        {"k2", cam.distortion_coefficients(1)},
        {"p1", cam.distortion_coefficients(2)},
        {"p2", cam.distortion_coefficients(3)},
        {"width", cam.resolution.at(0)},  {"height", cam.resolution.at(1)},
        {"model", cam.camera_model},      {"distortion_model", cam.distortion_model},
    };
}

json globalBaToJson(const GlobalBaReport& report) {
    return json{
        {"accepted", report.accepted},
        {"outcome", report.outcome},
        {"keyframes", report.keyframes},
        {"imu_factors", report.imu_factors},
        {"landmarks", report.landmarks},
        {"observations", report.observations},
        {"loop_observations", report.loop_observations},
        {"outliers_removed", report.outliers_removed},
        {"iterations", report.iterations},
        {"initial_error", report.initial_error},
        {"final_error", report.final_error},
        {"path_length_ratio", report.path_length_ratio},
        {"seconds", report.seconds},
    };
}

json loopClosureToJson(const LoopClosureReport& report) {
    json rejections = json::object();
    for (const auto& [gate, count] : report.rejections) {
        rejections[gate] = count;
    }

    json loops = json::array();
    for (const LoopClosureEdge& loop : report.loops) {
        loops.push_back(json{
            {"query", loop.query.v},
            {"candidate", loop.candidate.v},
            {"similarity", loop.similarity},
            {"matches", loop.matches},
            {"correspondences", loop.correspondences},
            {"inliers", loop.inliers},
            {"correction_translation_m", loop.correction_translation_m},
            {"correction_rotation_rad", loop.correction_rotation_rad},
        });
    }

    return json{
        {"model", report.model},
        {"keyframes", report.keyframes},
        {"nodes", report.nodes},
        {"queries", report.queries},
        {"queries_skipped", report.queries_skipped},
        {"candidates", report.candidates},
        {"rejections", std::move(rejections)},
        {"loops", std::move(loops)},
        {"mean_embed_ms", report.mean_embed_ms},
        {"mean_verify_ms", report.mean_verify_ms},
        {"global_ba",
         report.global_ba ? globalBaToJson(*report.global_ba) : json(nullptr)},
    };
}

std::optional<std::string> writeJson(const std::filesystem::path& path,
                                     const MapSnapshot& snap,
                                     const data::CamSensorParams& cam,
                                     const LoopClosureReport* loop_closure,
                                     std::string_view trajectory) {
    json doc;
    doc["format_version"] = kFormatVersion;
    // OpenCV convention: x-right, y-down, z-forward (along view direction).
    // Documented so the viewer can configure its scene axes consistently.
    doc["coordinate_system"] = "RDF";
    doc["camera"] = cameraToJson(cam);

    json keyframes = json::array();
    keyframes.get_ref<json::array_t&>().reserve(snap.keyframes.size());
    for (const auto& kf : snap.keyframes) {
        keyframes.push_back(poseToJson(kf));
    }
    doc["keyframes"] = std::move(keyframes);

    json ids = json::array();
    ids.get_ref<json::array_t&>().reserve(snap.landmarks.size());
    for (const auto& lm : snap.landmarks) {
        ids.push_back(lm.id.v);
    }
    doc["landmark_ids"] = std::move(ids);

    doc["stats"] = json{
        {"keyframes", snap.stats.keyframes},
        {"landmarks", snap.stats.landmarks},
        {"factors", snap.stats.factors},
    };

    // Optional: the gravity the IMU factors used (world frame), so an
    // evaluation can score the estimate's gravity direction
    if (!snap.gravity_world.isZero()) {
        doc["gravity_world"] = json::array({snap.gravity_world.x(),
                                            snap.gravity_world.y(),
                                            snap.gravity_world.z()});
    }

    // Optional: which estimate this file holds, and the loop closure outcome
    // (v2 with loop closure)
    doc["trajectory"] = trajectory;
    if (loop_closure != nullptr) {
        doc["loop_closure"] = loopClosureToJson(*loop_closure);
    }

    doc["created_at_unix"]
        = std::chrono::duration_cast<std::chrono::seconds>(
              std::chrono::system_clock::now().time_since_epoch())
              .count();

    std::ofstream f(path);
    if (!f) {
        return std::format("could not open '{}' for writing", path.string());
    }
    constexpr int kIndent = 2;
    f << doc.dump(kIndent) << '\n';
    if (!f) {
        return std::format("write error on '{}'", path.string());
    }
    return std::nullopt;
}

